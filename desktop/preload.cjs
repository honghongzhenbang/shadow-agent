const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("shadowPet", {
  snapshot: () => ipcRenderer.invoke("pet:snapshot"),
  openClawStatus: () => ipcRenderer.invoke("pet:openclaw-status"),
  attentionSchedule: () => ipcRenderer.invoke("pet:attention-schedule"),
  updateAttentionSchedule: (input) => ipcRenderer.invoke("pet:update-attention-schedule", input),
  submitManualInput: (text) => ipcRenderer.invoke("pet:submit-manual-input", text),
  mainConversation: (options = {}) => ipcRenderer.invoke("pet:main-conversation", options),
  taskConversation: (id, options = {}) => ipcRenderer.invoke("pet:task-conversation", id, options),
  agentHistory: (options = {}) => ipcRenderer.invoke("pet:agent-history", options),
  agentHistoryDetails: (id) => ipcRenderer.invoke("pet:agent-history-details", id),
  taskDetails: (id, options = {}) => ipcRenderer.invoke("pet:task-details", id, options),
  closeTask: (id, input) => ipcRenderer.invoke("pet:close-task", id, input),
  confirmTaskDone: (id, note = "") => ipcRenderer.invoke("pet:confirm-task-done", id, note),
  sendTaskMessage: (id, message) => ipcRenderer.invoke("pet:send-task-message", id, message),
  acknowledgeReminder: (id) => ipcRenderer.invoke("pet:acknowledge-reminder", id),
  snoozeReminder: (id, minutes = 10) => ipcRenderer.invoke("pet:snooze-reminder", id, minutes),
  updateReminder: (id, changes = {}) => ipcRenderer.invoke("pet:update-reminder", id, changes),
  cancelReminder: (id) => ipcRenderer.invoke("pet:cancel-reminder", id),
  approveOutboundMessage: (id, content) => ipcRenderer.invoke("pet:approve-outbound-message", id, content),
  cancelOutboundMessage: (id, reason) => ipcRenderer.invoke("pet:cancel-outbound-message", id, reason),
  setExpanded: (value) => ipcRenderer.invoke("pet:set-expanded", Boolean(value)),
  setPinned: (value) => ipcRenderer.invoke("pet:set-pinned", Boolean(value)),
  hide: () => ipcRenderer.invoke("pet:hide"),
  onExpanded: (callback) => ipcRenderer.on("pet:expanded", (_event, value) => callback(Boolean(value))),
  onOpenClawStatus: (callback) => ipcRenderer.on("pet:openclaw-status", (_event, value) => callback(value)),
  onAttentionSchedule: (callback) => ipcRenderer.on("pet:attention-schedule", (_event, value) => callback(value)),
});
